#!/usr/bin/env python3
"""End-to-end sanitized reproduction of the WA-018 result from a clean clone.

Regenerates the calibration capsule from immutable repository evidence, reruns
the full focused suite, regenerates the frontier grid and threshold cases, and
compares every regenerated artifact byte for byte against the committed one.

Any difference is reported as a failure, because a result that cannot be
regenerated byte-identically from its own committed inputs is not reproducible.

Usage:
    reproduce_all.py [--repo <path>] [--commit <sha>] [--out <file>]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
DEFAULT_COMMIT = "48ac81e2580c6efefae8de39dc6b484b57e5c881"
REPRODUCTION_ID = "R-PO03-WA-018-001"

REGENERATED = (
    ("calibration-capsule.json", "calibration"),
    ("frontier-results.json", "threshold_cases"),
    ("threshold-case-results.json", "threshold_cases"),
)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _run(args: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True)


def _volatile_free(name: str, data: bytes) -> bytes:
    """Strip the one field that legitimately varies between identical runs.

    compute_seconds records how long the grid took on this host. It is execution
    evidence, not a result, so it is excluded from the byte comparison and the
    exclusion is reported rather than applied silently.
    """
    if name not in {"frontier-results.json", "threshold-case-results.json"}:
        return data
    document = json.loads(data.decode("utf-8"))
    document.pop("compute_seconds", None)
    return (json.dumps(document, indent=2, sort_keys=True) + "\n").encode("utf-8")


def reproduce(repo: Path, commit: str) -> dict[str, Any]:
    stages: list[dict[str, Any]] = []
    with tempfile.TemporaryDirectory(prefix="wa018-repro-") as scratch:
        work = Path(scratch)

        suite = _run(
            [sys.executable, "-m", "unittest", "discover", "-s", ".", "-p", "test_*.py"],
            HERE,
        )
        test_lines = suite.stderr.strip().splitlines()
        stages.append(
            {
                "stage": "focused_suite",
                "command": "python3 -m unittest discover -s . -p 'test_*.py'",
                "exit_code": suite.returncode,
                "state": "PASS" if suite.returncode == 0 else "FAIL",
                "summary": test_lines[-1] if test_lines else "",
                "tests_run": next(
                    (
                        int(line.split()[1])
                        for line in test_lines
                        if line.startswith("Ran ")
                    ),
                    None,
                ),
            }
        )

        capsule = _run(
            [
                sys.executable,
                str(HERE / "calibrate_from_repository.py"),
                "--commit",
                commit,
                "--repo",
                str(repo),
                "--out",
                str(work / "calibration-capsule.json"),
            ],
            work,
        )
        stages.append(
            {
                "stage": "calibration",
                "command": f"calibrate_from_repository.py --commit {commit}",
                "exit_code": capsule.returncode,
                "state": "PASS" if capsule.returncode == 0 else "FAIL",
                "stderr": capsule.stderr.strip()[:2000],
            }
        )

        cases = _run(
            [
                sys.executable,
                str(HERE / "threshold_cases.py"),
                "--out-frontier",
                str(work / "frontier-results.json"),
                "--out-cases",
                str(work / "threshold-case-results.json"),
            ],
            HERE,
        )
        stages.append(
            {
                "stage": "threshold_cases",
                "command": "threshold_cases.py",
                "exit_code": cases.returncode,
                "state": "PASS" if cases.returncode == 0 else "FAIL",
                "stdout": cases.stdout.strip()[:2000],
            }
        )

        comparisons: list[dict[str, Any]] = []
        for name, stage in REGENERATED:
            committed = _volatile_free(name, (HERE / name).read_bytes())
            regenerated_path = work / name
            if not regenerated_path.exists():
                comparisons.append(
                    {"artifact": name, "state": "MISSING", "stage": stage}
                )
                continue
            regenerated = _volatile_free(name, regenerated_path.read_bytes())
            comparisons.append(
                {
                    "artifact": name,
                    "stage": stage,
                    "committed_sha256": _sha(committed),
                    "regenerated_sha256": _sha(regenerated),
                    "committed_bytes": len(committed),
                    "regenerated_bytes": len(regenerated),
                    "state": "IDENTICAL" if committed == regenerated else "DIVERGED",
                    "volatile_fields_excluded": (
                        ["compute_seconds"]
                        if name != "calibration-capsule.json"
                        else []
                    ),
                }
            )

    all_pass = all(stage["state"] == "PASS" for stage in stages) and all(
        item["state"] == "IDENTICAL" for item in comparisons
    )
    return {
        "reproduction_id": REPRODUCTION_ID,
        "protocol_version": "OBZIO-WA-018-REPRODUCTION-v1",
        "task_id": "PO03-WA-018",
        "immutable_commit": commit,
        "sanitized": True,
        "sanitization_note": (
            "Only committed PO-03 control and metrics evidence is read, through "
            "git show at an immutable commit. No secret, credential, provider "
            "identifier or environment value enters any artifact."
        ),
        "repository_native": True,
        "stages": stages,
        "artifact_comparisons": comparisons,
        "state": "PASS" if all_pass else "FAIL",
        "recurrence_instructions": [
            "git clone --no-hardlinks <repository> fresh && cd fresh",
            "git checkout cursor/po03-wa-018-b195-a02-1a9f",
            "cd workstreams/po03/wave-a/units/wa-018/result",
            f"python3 reproduce_all.py --repo ../../../../../.. --commit {commit}",
        ],
        "dependencies": "CPython standard library only, plus git on PATH",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", default=str(HERE.parents[5]))
    parser.add_argument("--commit", default=DEFAULT_COMMIT)
    parser.add_argument("--out", default="-")
    args = parser.parse_args()
    report = reproduce(Path(args.repo).resolve(), args.commit)
    text = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.out == "-":
        print(text, end="")
    else:
        Path(args.out).write_text(text, encoding="utf-8")
        print(json.dumps({"state": report["state"], "wrote": args.out}, sort_keys=True))
    return 0 if report["state"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
