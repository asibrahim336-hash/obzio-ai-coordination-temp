#!/usr/bin/env python3
"""Route-01 result staging: build a task manifest and transactional result.

Standard library only so a clean clone reproduces identical artifact digests.
This tool performs custody bookkeeping for a task slot; it is deliberately not
the falsifiable component under test for any task.  Each task's component and
tests live entirely inside that task's own result slot.

The producer ceiling is READY_TO_COMMIT.  This tool refuses to emit
``COMPLETED`` or an ``ACCEPTED`` independent acceptance, so a producer cannot
self-certify coordinator completion or independent acceptance.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

COMMISSION_ID = "COM-PO03-REPOSITORY-ENGINEERING-PORTABLE-RUNTIME-20260822-v001"
PROTOCOL_VERSION = "OBZIO-TRANSACTIONAL-RESULT-v1"
WAVE_ID = "PO03-WAVE-A-20260822"
ROUTE_ID = "route-01"
ROUTE_SLOT = "workstreams/po03/runs/wave-a/route-01"
IMMUTABLE_BASE = "44de68e52a0baa480a8a8c0b95fd5071391dd4a1"
SOURCE_LOCK_URI = "workstreams/po03/evidence/source-lock.json"
WORKER_ID = "route-01-material-worker"

# Producer-side states this tool is permitted to write.
PRODUCER_STATES = ("RESULT_STAGING", "RESULT_STAGED")
FORBIDDEN_STATES = ("RESULT_COMMITTED", "PARENT_INGESTED", "COMPLETED")

MEDIA_TYPES = {
    ".py": "text/x-python",
    ".json": "application/json",
    ".md": "text/markdown",
    ".txt": "text/plain",
    ".jsonl": "application/x-ndjson",
}

# Files generated by this tool; never self-referential manifest entries.
GENERATED = {"manifest.json", "result.json"}


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def digest_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        directory_fd = os.open(path.parent, os.O_DIRECTORY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def write_json(path: Path, value: Any) -> bytes:
    data = json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False).encode() + b"\n"
    atomic_write(path, data)
    return data


def collect_artifacts(slot: Path) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    for path in sorted(slot.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(slot).as_posix()
        if relative in GENERATED or "__pycache__" in relative:
            continue
        payload = path.read_bytes()
        entries.append(
            {
                "artifact_id": f"{slot.name}:{relative}",
                "logical_name": relative,
                "content_uri": f"{ROUTE_SLOT}/{slot.name}/{relative}",
                "sha256": digest_bytes(payload),
                "bytes": len(payload),
                "media_type": MEDIA_TYPES.get(path.suffix, "application/octet-stream"),
            }
        )
    return entries


def stage(
    slot: Path,
    task_id: str,
    hypothesis: str,
    disposition: str,
    obzio_state: str,
    provider_state: str,
    acceptance_sha: str,
    input_manifest_sha: str,
    provider_run_id: str,
    commands: list[str],
    limitations: list[str],
) -> dict[str, Any]:
    if obzio_state in FORBIDDEN_STATES:
        raise SystemExit(f"producer ceiling violation: {obzio_state} is above READY_TO_COMMIT")
    if obzio_state not in PRODUCER_STATES:
        raise SystemExit(f"unsupported producer state: {obzio_state}")

    artifacts = collect_artifacts(slot)
    if not artifacts:
        raise SystemExit(f"no artifacts found in {slot}")
    staged_at = utc_now()

    manifest = {
        "manifest_version": "PO03-ROUTE-01-TASK-MANIFEST-v1",
        "wave_id": WAVE_ID,
        "route_id": ROUTE_ID,
        "task_id": task_id,
        "commission_id": COMMISSION_ID,
        "frozen_hypothesis": hypothesis,
        "immutable_base_commit": IMMUTABLE_BASE,
        "source_lock_uri": SOURCE_LOCK_URI,
        "immutable_input_manifest_sha256": input_manifest_sha,
        "acceptance_contract_uri": f"workstreams/po03/control/tasks/{task_id}/acceptance.json",
        "acceptance_contract_sha256": acceptance_sha,
        "exact_model_configuration": "claude-opus-5-thinking-high",
        "commands": commands,
        "disposition": disposition,
        "limitations": limitations,
        "producer_terminal_report": "READY_TO_COMMIT",
        "independent_acceptance": "NOT_TESTED",
        "artifact_count": len(artifacts),
        "total_bytes": sum(item["bytes"] for item in artifacts),
        "artifacts": artifacts,
        "staged_at": staged_at,
        "decision_changed": [],
    }
    manifest_bytes = write_json(slot / "manifest.json", manifest)
    manifest_sha = digest_bytes(manifest_bytes)

    # Read back every artifact from disk before declaring the slot staged.
    verified_at = utc_now()
    for item in artifacts:
        payload = (slot / item["logical_name"]).read_bytes()
        if digest_bytes(payload) != item["sha256"] or len(payload) != item["bytes"]:
            raise SystemExit(f"readback mismatch for {item['logical_name']}")
        item["readback_verified_at"] = verified_at

    result = {
        "protocol_version": PROTOCOL_VERSION,
        "task_id": task_id,
        "commission_id": COMMISSION_ID,
        "immutable_input_manifest_sha256": input_manifest_sha,
        "acceptance_contract_sha256": acceptance_sha,
        "provider_state": provider_state,
        "obzio_state": obzio_state,
        "attempt": {
            "attempt_id": f"{task_id}-attempt-1",
            "idempotency_key": f"{WAVE_ID}:{task_id}:attempt-1",
            "lease_id": f"lease-{task_id}-1",
            "fence_token": 1,
            "provider_run_id": provider_run_id,
            "worker_id": WORKER_ID,
            "heartbeat_at": verified_at,
            "checkpoint_seq": 1,
        },
        "result_transaction": {
            "result_txn_id": f"rtxn-{task_id}-1",
            "state": "STAGED",
            "manifest_uri": f"{ROUTE_SLOT}/{task_id}/manifest.json",
            "manifest_sha256": manifest_sha,
            "artifact_count": len(artifacts),
            "total_bytes": sum(item["bytes"] for item in artifacts),
            "committed_at": None,
            "verified_at": verified_at,
            "parent_ingested_at": None,
            "result_commit_id": None,
        },
        "artifacts": artifacts,
        "completion_actor": None,
        "independent_acceptance": {"state": "NOT_TESTED", "reviewer_id": None, "receipt_uri": None},
    }
    write_json(slot / "result.json", result)
    print(
        f"STAGED {task_id} obzio_state={obzio_state} disposition={disposition} "
        f"artifacts={len(artifacts)} bytes={manifest['total_bytes']} manifest_sha256={manifest_sha}"
    )
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--slot", type=Path, required=True)
    parser.add_argument("--task-id", required=True)
    parser.add_argument("--hypothesis", required=True)
    parser.add_argument("--disposition", required=True)
    parser.add_argument("--obzio-state", default="RESULT_STAGED")
    parser.add_argument("--provider-state", default="RUNNING")
    parser.add_argument("--acceptance-sha", required=True)
    parser.add_argument("--input-manifest-sha", required=True)
    parser.add_argument("--provider-run-id", required=True)
    parser.add_argument("--command", action="append", default=[])
    parser.add_argument("--limitation", action="append", default=[])
    args = parser.parse_args(argv)
    stage(
        slot=args.slot.resolve(),
        task_id=args.task_id,
        hypothesis=args.hypothesis,
        disposition=args.disposition,
        obzio_state=args.obzio_state,
        provider_state=args.provider_state,
        acceptance_sha=args.acceptance_sha,
        input_manifest_sha=args.input_manifest_sha,
        provider_run_id=args.provider_run_id,
        commands=args.command,
        limitations=args.limitation,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
